import { mkdir, readdir, unlink, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { optimize } from 'svgo';

const svgDirectory = new URL('../svg/resources/', import.meta.url);
const enumPath = new URL('../src/KeylineIcon.php', import.meta.url);
const variants = [
    ['duotone', 'duotone', 'Duotone'],
    ['fill', 'fill', 'Fill'],
    ['', 'rounded', ''],
    ['sharp', 'sharp', 'Sharp'],
    ['sharp/duotone', 'sharp-duotone', 'SharpDuotone'],
    ['sharp/fill', 'sharp-fill', 'SharpFill'],
];

const icons = new Map();
const cases = new Map();
let rawBytes = 0;
let optimizedBytes = 0;

// Render the package's public exports, which resolve to the dist modules.
// Finish rendering and validation before touching the previous build.
for (const [entry, suffix, caseSuffix] of variants) {
    const components = await import(`@keyline-icons/react${entry ? `/${entry}` : ''}`);
    const names = Object.keys(components).sort();
    if (names.length === 0) throw new Error(`No icons found for ${suffix}`);

    for (const name of names) {
        const slug = name
            .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
            .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
            .toLowerCase();
        const filename = `${slug}-${suffix}.svg`;
        const caseName = `${name}${caseSuffix}`;
        if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(caseName)) {
            throw new Error(`Invalid PHP case name: ${caseName}`);
        }
        if (icons.has(filename) || cases.has(caseName.toLowerCase())) {
            throw new Error(`Duplicate icon or enum case: ${filename}, ${caseName}`);
        }

        const raw = renderToStaticMarkup(createElement(components[name]));
        if (!raw.startsWith('<svg ')) throw new Error(`Not an SVG: ${name}`);
        const { data } = optimize(raw, {
            path: filename,
            multipass: true,
            plugins: ['preset-default'],
        });
        icons.set(filename, `${data}\n`);
        cases.set(caseName.toLowerCase(), { name: caseName, value: `keyline-${slug}-${suffix}` });
        rawBytes += Buffer.byteLength(raw);
        optimizedBytes += Buffer.byteLength(data);
    }
    console.log(`${suffix}: ${names.length} icons`);
}

const enumCases = [...cases.values()]
    .sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)
    .map(({ name, value }) => `    case ${name} = '${value}';`)
    .join('\n');
const php = `<?php\n\nnamespace Anodyne\\KeylineIcons;\n\n// Generated by bun run build. Do not edit manually.\nenum KeylineIcon: string\n{\n${enumCases}\n}\n`;

await mkdir(svgDirectory, { recursive: true });
await mkdir(new URL('../src/', import.meta.url), { recursive: true });
for (const [filename, svg] of icons) {
    await writeFile(new URL(filename, svgDirectory), svg);
}
// This directory is generated: remove icons no longer exported upstream.
for (const filename of await readdir(svgDirectory)) {
    if (filename.endsWith('.svg') && !icons.has(filename)) {
        await unlink(new URL(filename, svgDirectory));
    }
}
await writeFile(enumPath, php);
console.log(`Generated ${icons.size} optimized SVGs in ${fileURLToPath(svgDirectory)}`);
console.log(`Generated ${cases.size} cases in ${fileURLToPath(enumPath)}`);
console.log(`SVGO: ${rawBytes} → ${optimizedBytes} bytes (${((1 - optimizedBytes / rawBytes) * 100).toFixed(1)}% smaller)`);
